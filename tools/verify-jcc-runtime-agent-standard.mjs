async function readText(file) {
  return readFile(file, "utf8");
}

function assertContains(text, needle, file) {
  if (!text.includes(needle)) throw new Error(`${file} missing required text: ${needle}`);
}

function assertNotContains(text, needle, file) {
  if (needle && text.includes(needle)) throw new Error(`${file} contains forbidden text: ${needle}`);
}

async function main() {
  const results = [];
  for (const check of CHECKS) {
    const text = await readText(check.file);
    for (const needle of check.required) assertContains(text, needle, check.file);
    for (const needle of check.forbidden || []) assertNotContains(text, needle, check.file);
    results.push({ file: check.file, required: check.required.length, forbidden: (check.forbidden || []).length });
  }
  process.stdout.write(`${JSON.stringify({ ok: true, checks: results }, null, 2)}\n`);
}

main().catch((error) => {
  console.error(error?.stack || error?.message || String(error));
  process.exitCode = 1;
});
